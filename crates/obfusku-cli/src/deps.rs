//! Dependencies (`ADR-029`): `[dependencies]` entries are local paths or
//! git repositories (GitHub, GitLab or any URL `git` can clone). A git
//! dependency is pinned to a commit in `obfusku.lock` by `obfusku fetch`
//! and materialized under the cache; `run`/`check` never touch the
//! network and fail with a pointer to `fetch` when something is missing.

use crate::manifest::{DependencySource, GitRef, MANIFEST_FILE_NAME, load_manifest};
use obfusku_diagnostics::{Diagnostic, Severity, Span};
use std::collections::{BTreeMap, HashMap, HashSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

pub const LOCK_FILE_NAME: &str = "obfusku.lock";

/// Directories of a dependency that are not importable modules.
pub(crate) const AUXILIARY_DIRS: [&str; 3] = ["tests", "examples", "benches"];

/// Each package root and the roots of its direct dependencies.
#[derive(Debug, Clone, Default)]
pub struct Packages {
    deps_of: HashMap<PathBuf, Vec<PathBuf>>,
}

impl Packages {
    #[must_use]
    pub fn new(deps_of: HashMap<PathBuf, Vec<PathBuf>>) -> Self {
        Packages { deps_of }
    }

    /// The direct dependency roots of the package rooted at `root`.
    #[must_use]
    pub fn dependency_roots(&self, root: &Path) -> &[PathBuf] {
        if self.deps_of.is_empty() {
            return &[];
        }
        let key = root.canonicalize().unwrap_or_else(|_| root.to_path_buf());
        self.deps_of.get(&key).map_or(&[], Vec::as_slice)
    }

    #[must_use]
    pub fn edges(&self) -> &HashMap<PathBuf, Vec<PathBuf>> {
        &self.deps_of
    }
}

fn error(message: impl Into<String>) -> Diagnostic {
    Diagnostic {
        severity: Severity::Error,
        message: message.into(),
        primary: Span::default(),
    }
}

/// `$OBFUSKU_HOME`, else `~/.obfusku`.
#[must_use]
pub fn cache_root() -> PathBuf {
    if let Some(home) = std::env::var_os("OBFUSKU_HOME") {
        return PathBuf::from(home);
    }
    let home = std::env::var_os("HOME")
        .or_else(|| std::env::var_os("USERPROFILE"))
        .map_or_else(|| PathBuf::from("."), PathBuf::from);
    home.join(".obfusku")
}

/// A short, stable directory name for `url`: its last segment plus an
/// FNV-1a hash. The full URL as a name overruns Windows' 260-character
/// path limit once git adds `.git/objects/xx/…` below it.
fn slug(url: &str) -> String {
    let hash = url.bytes().fold(0xcbf2_9ce4_8422_2325_u64, |h, b| {
        (h ^ u64::from(b)).wrapping_mul(0x0100_0000_01b3)
    });
    let last = url
        .trim_end_matches(['/', '\\'])
        .rsplit(['/', '\\', ':'])
        .next()
        .unwrap_or("");
    let name: String = last
        .trim_end_matches(".git")
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '-' {
                c
            } else {
                '_'
            }
        })
        .take(24)
        .collect();
    format!("{name}-{hash:016x}")
}

fn package_dir(url: &str, rev: &str) -> PathBuf {
    cache_root().join("git").join(slug(url)).join(rev)
}

/// One pinned git dependency, as recorded in `obfusku.lock`.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
struct LockEntry {
    source: String,
    reference: String,
    rev: String,
}

fn read_lock(root: &Path) -> Result<Vec<LockEntry>, Diagnostic> {
    let path = root.join(LOCK_FILE_NAME);
    let Ok(text) = std::fs::read_to_string(&path) else {
        return Ok(Vec::new());
    };
    let value: toml::Value = text
        .parse()
        .map_err(|e| error(format!("invalid lock file '{}': {e}", path.display())))?;
    let mut out = Vec::new();
    for pkg in value
        .get("package")
        .and_then(toml::Value::as_array)
        .into_iter()
        .flatten()
    {
        let field = |k: &str| pkg.get(k).and_then(toml::Value::as_str).map(str::to_string);
        match (field("source"), field("ref"), field("rev")) {
            (Some(source), Some(reference), Some(rev)) => out.push(LockEntry {
                source,
                reference,
                rev,
            }),
            _ => {
                return Err(error(format!(
                    "invalid lock file '{}': a [[package]] needs source, ref and rev",
                    path.display()
                )));
            }
        }
    }
    Ok(out)
}

fn write_lock(root: &Path, entries: &BTreeMap<(String, String), String>) -> Result<(), Diagnostic> {
    let mut text = String::from(
        "# Generated by `obfusku fetch`. Commit it: it pins every git dependency to a commit.\n\
         version = 1\n",
    );
    for ((source, reference), rev) in entries {
        let _ = write!(
            text,
            "\n[[package]]\nsource = {source:?}\nref = {reference:?}\nrev = {rev:?}\n"
        );
    }
    let path = root.join(LOCK_FILE_NAME);
    std::fs::write(&path, text)
        .map_err(|e| error(format!("could not write '{}': {e}", path.display())))
}

fn git(args: &[&str], dir: Option<&Path>) -> Result<String, String> {
    let mut cmd = Command::new("git");
    cmd.args(args).env("GIT_TERMINAL_PROMPT", "0");
    if let Some(d) = dir {
        cmd.current_dir(d);
    }
    let out = cmd
        .output()
        .map_err(|e| format!("could not run 'git' ({e}); git is needed to fetch dependencies"))?;
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
    } else {
        Err(String::from_utf8_lossy(&out.stderr).trim().to_string())
    }
}

fn is_full_sha(s: &str) -> bool {
    s.len() == 40 && s.bytes().all(|b| b.is_ascii_hexdigit())
}

/// The commit a tag, branch or revision currently names on `url`.
fn resolve_rev(url: &str, reference: &GitRef) -> Result<String, String> {
    match reference {
        GitRef::Rev(r) if is_full_sha(r) => Ok(r.clone()),
        GitRef::Rev(r) => Err(format!(
            "'rev' must be a full 40-character commit hash, found '{r}'"
        )),
        GitRef::Tag(t) => {
            let peeled = format!("refs/tags/{t}^{{}}");
            let plain = format!("refs/tags/{t}");
            let out = git(&["ls-remote", "--", url, &peeled, &plain], None)?;
            // An annotated tag lists its commit on the peeled line.
            let line = out
                .lines()
                .find(|l| l.ends_with("^{}"))
                .or_else(|| out.lines().next())
                .ok_or_else(|| format!("tag '{t}' not found in {url}"))?;
            Ok(line
                .split_whitespace()
                .next()
                .unwrap_or_default()
                .to_string())
        }
        GitRef::Branch(b) => {
            let out = git(&["ls-remote", "--", url, &format!("refs/heads/{b}")], None)?;
            out.split_whitespace()
                .next()
                .map(str::to_string)
                .ok_or_else(|| format!("branch '{b}' not found in {url}"))
        }
    }
}

/// Materializes `rev` of `url` into the cache (once) and returns its root.
fn materialize(url: &str, rev: &str) -> Result<PathBuf, String> {
    let dest = package_dir(url, rev);
    if dest.is_dir() {
        return Ok(dest);
    }
    let parent = dest.parent().expect("package_dir has a parent");
    std::fs::create_dir_all(parent).map_err(|e| format!("could not create cache: {e}"))?;
    let tmp = parent.join(format!(".{rev}.tmp{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    let attempt = (|| -> Result<(), String> {
        std::fs::create_dir_all(&tmp).map_err(|e| e.to_string())?;
        git(&["init", "-q"], Some(&tmp))?;
        git(&["remote", "add", "--", "origin", url], Some(&tmp))?;
        // Servers that refuse a fetch by hash get a full clone instead.
        if git(&["fetch", "-q", "--depth", "1", "origin", rev], Some(&tmp)).is_ok() {
            git(&["checkout", "-q", "FETCH_HEAD"], Some(&tmp))?;
        } else {
            git(&["fetch", "-q", "origin"], Some(&tmp))?;
            git(&["checkout", "-q", rev], Some(&tmp))?;
        }
        let head = git(&["rev-parse", "HEAD"], Some(&tmp))?;
        if head != rev {
            return Err(format!("expected commit {rev}, got {head}"));
        }
        Ok(())
    })();
    if let Err(e) = attempt {
        let _ = std::fs::remove_dir_all(&tmp);
        return Err(e);
    }
    let _ = std::fs::remove_dir_all(tmp.join(".git"));
    if let Err(e) = std::fs::rename(&tmp, &dest) {
        let _ = std::fs::remove_dir_all(&tmp);
        // A parallel fetch stored the same commit first: same content.
        if !dest.is_dir() {
            return Err(format!("could not store the dependency: {e}"));
        }
    }
    Ok(dest)
}

struct Walker<'a> {
    lock: &'a [LockEntry],
    /// `Some` when fetching; `None` offline.
    fetch: Option<FetchState>,
    deps_of: HashMap<PathBuf, Vec<PathBuf>>,
    visited: HashSet<PathBuf>,
}

struct FetchState {
    update: bool,
    pinned: BTreeMap<(String, String), String>,
    report: Vec<String>,
}

impl Walker<'_> {
    fn git_root(
        &mut self,
        name: &str,
        url: &str,
        reference: &GitRef,
    ) -> Result<PathBuf, Diagnostic> {
        let key = (url.to_string(), reference.key());
        let locked = self
            .lock
            .iter()
            .find(|e| e.source == key.0 && e.reference == key.1)
            .map(|e| e.rev.clone());
        let Some(state) = self.fetch.as_mut() else {
            let rev = locked.ok_or_else(|| {
                error(format!(
                    "dependency '{name}' is not locked; run 'obfusku fetch' to resolve it"
                ))
            })?;
            let dir = package_dir(url, &rev);
            return if dir.is_dir() {
                Ok(dir)
            } else {
                Err(error(format!(
                    "dependency '{name}' ({}) is not in the cache; run 'obfusku fetch'",
                    &rev[..rev.len().min(12)]
                )))
            };
        };
        let rev = match locked {
            Some(rev) if !state.update => rev,
            _ => resolve_rev(url, reference)
                .map_err(|e| error(format!("dependency '{name}': {e}")))?,
        };
        let existed = package_dir(url, &rev).is_dir();
        let dir = materialize(url, &rev).map_err(|e| error(format!("dependency '{name}': {e}")))?;
        state.pinned.insert(key, rev.clone());
        state.report.push(format!(
            "{} {name} {} ({})",
            if existed { "cached" } else { "fetched" },
            &rev[..12],
            reference.key()
        ));
        Ok(dir)
    }

    fn visit(&mut self, root: &Path) -> Result<(), Diagnostic> {
        let root = root.canonicalize().map_err(|e| {
            error(format!(
                "dependency root '{}' is not readable: {e}",
                root.display()
            ))
        })?;
        if !self.visited.insert(root.clone()) {
            return Ok(());
        }
        if !root.join(MANIFEST_FILE_NAME).is_file() {
            return Ok(());
        }
        let manifest = load_manifest(&root)?;
        let mut roots = Vec::new();
        for dep in &manifest.dependencies {
            let dep_root = match &dep.source {
                DependencySource::Path(p) => {
                    let candidate = root.join(p);
                    candidate.canonicalize().map_err(|e| {
                        error(format!(
                            "dependency '{}': path '{}' is not readable: {e}",
                            dep.name,
                            candidate.display()
                        ))
                    })?
                }
                DependencySource::Git { url, reference } => {
                    self.git_root(&dep.name, url, reference)?
                }
            };
            roots.push(dep_root.canonicalize().unwrap_or(dep_root.clone()));
            self.visit(&dep_root)?;
        }
        if !roots.is_empty() {
            self.deps_of.insert(root, roots);
        }
        Ok(())
    }
}

/// The package graph under `root` from `obfusku.lock` and the cache.
/// Fails, naming `obfusku fetch`, when a git dependency is not locked or
/// not cached.
pub fn load_packages(root: &Path) -> Result<Packages, Diagnostic> {
    let lock = read_lock(root)?;
    let mut walker = Walker {
        lock: &lock,
        fetch: None,
        deps_of: HashMap::new(),
        visited: HashSet::new(),
    };
    walker.visit(root)?;
    Ok(Packages::new(walker.deps_of))
}

/// `obfusku fetch`: resolves every git dependency under `root` (reusing
/// the lock unless `update`), fills the cache and rewrites `obfusku.lock`.
/// Returns one report line per git package.
pub fn fetch(root: &Path, update: bool) -> Result<Vec<String>, Diagnostic> {
    let lock = if update { Vec::new() } else { read_lock(root)? };
    let mut walker = Walker {
        lock: &lock,
        fetch: Some(FetchState {
            update,
            pinned: BTreeMap::new(),
            report: Vec::new(),
        }),
        deps_of: HashMap::new(),
        visited: HashSet::new(),
    };
    walker.visit(root)?;
    let state = walker.fetch.expect("fetch state set above");
    if state.pinned.is_empty() {
        let lock_path = root.join(LOCK_FILE_NAME);
        if lock_path.is_file() {
            std::fs::remove_file(&lock_path).ok();
        }
        return Ok(vec!["no git dependencies".to_string()]);
    }
    write_lock(root, &state.pinned)?;
    Ok(state.report)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("obk-deps-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn a_path_dependency_and_its_own_dependency_form_a_graph() {
        let base = scratch("graph");
        let (app, lib, leaf) = (base.join("app"), base.join("lib"), base.join("leaf"));
        for d in [&app, &lib, &leaf] {
            std::fs::create_dir_all(d).unwrap();
        }
        std::fs::write(
            app.join("obfusku.toml"),
            "format = 2\nentry = \"main\"\n[dependencies]\nlib = { path = \"../lib\" }\n",
        )
        .unwrap();
        std::fs::write(
            lib.join("obfusku.toml"),
            "format = 2\nentry = \"x\"\n[dependencies]\nleaf = { path = \"../leaf\" }\n",
        )
        .unwrap();
        let packages = load_packages(&app).unwrap();
        let lib_c = lib.canonicalize().unwrap();
        assert_eq!(
            packages.dependency_roots(&app),
            std::slice::from_ref(&lib_c)
        );
        assert_eq!(
            packages.dependency_roots(&lib_c),
            [leaf.canonicalize().unwrap()]
        );
        let _ = std::fs::remove_dir_all(base);
    }

    #[test]
    fn an_unlocked_git_dependency_asks_for_fetch_instead_of_hitting_the_network() {
        let dir = scratch("unlocked");
        std::fs::write(
            dir.join("obfusku.toml"),
            "format = 2\nentry = \"main\"\n[dependencies]\nx = { github = \"o/r\", tag = \"v1\" }\n",
        )
        .unwrap();
        let e = load_packages(&dir).unwrap_err();
        assert!(e.message.contains("obfusku fetch"), "{}", e.message);
        let _ = std::fs::remove_dir_all(dir);
    }

    #[test]
    fn rev_must_be_a_full_hash() {
        assert!(resolve_rev("u", &GitRef::Rev("abc".into())).is_err());
        let sha = "a".repeat(40);
        assert_eq!(resolve_rev("u", &GitRef::Rev(sha.clone())).unwrap(), sha);
    }
}
